const dir = await fs.mkdtemp(path.join(os.tmpdir(), 'bi-v03-'));
const ifcPath = path.join(dir, 'data', 'demo_set', 'house3.ifc');
await fs.mkdir(path.dirname(ifcPath), { recursive: true });
await fs.writeFile(ifcPath, IFC);
const env = { CORRECTIONS_FILE: path.join(dir, 'none.json') };
const run = (out, extra = {}) => processBlueprint({ inputFilePath: ifcPath, outputJsonPath: path.join(dir, 'out', out), env, logger: silentLogger, ...extra });
const read = async (p) => JSON.parse(await fs.readFile(p, 'utf8'));
const v = await createVersionedValidator();

const res = await run('house3.json');
const doc = await read(res.outputs[0].outputJsonPath);
const by = (coll, guid) => doc[coll].find(e=>e.ifc_global_id===guid);
const wall=by('walls','0wall1'),door=by('openings','0door1'),room=by('rooms','0space1');
const quantity=(entity,name)=>entity.quantities.find(q=>q.name===name);

test('canonical v0.3 IFC validates with every reference resolved',()=>{
  assert.equal(doc.schema_version,'0.3');
  assert.deepEqual(v.describe(v.validate(doc)),[]);
  assert.deepEqual(validateRelationships(doc),[]);
  assert.ok(!('drawing' in doc));
});
test('project and source retain declared units and application metadata',()=>{
  assert.equal(doc.project.name,'Demo');
  assert.equal(doc.project.building_name,'House');
  assert.equal(doc.project.ifc_schema,'IFC4');
  assert.equal(doc.source_documents[0].format,'ifc');
  assert.equal(doc.source_documents[0].units.to_si.LENGTHUNIT,.001);
  assert.equal(doc.source_documents[0].units.to_si.AREAUNIT,1);
  assert.ok(Math.abs(doc.source_documents[0].units.to_si.PLANEANGLEUNIT-Math.PI/180)<1e-12);
  assert.ok(doc.source_documents[0].properties.applications.some(a=>a.args.includes('Demo CAD')));
});
test('space uses source quantities before calculated geometry and retains boundaries and finishes',()=>{
  assert.equal(room.area_computed_m2,12);
  assert.equal(room.area_m2,11.5);
  assert.equal(room.volume_m3,31.05);
  assert.equal(room.height_m,2.7);
  assert.equal(quantity(room,'NetFloorArea').origin,'source');
  assert.equal(quantity(room,'area_computed_m2').origin,'calculated');
  assert.equal(room.finishes.find(f=>f.surface==='floor').description,'Oak parquet');
  assert.deepEqual(room.boundary_ids,[wall.id]);
  assert.deepEqual(wall.room_ids,[room.id]);
});
test('wall retains material order, SI thickness, quantity provenance and classification',()=>{
  assert.deepEqual(wall.material_layers.map(l=>[l.material.name,l.thickness_m]),[['Concrete',.15],['Insulation',.05]]);
  assert.equal(wall.thickness_m,.2);
  assert.equal(wall.material_layers[1].is_ventilated,false);
  assert.equal(quantity(wall,'thickness_m').method,'sum of IfcMaterialLayer.LayerThickness');
  assert.equal(wall.length_m,4);
  assert.equal(quantity(wall,'Length').original_value,4000);
  assert.equal(wall.classifications[0].code,'Ss_25_10');
});
test('door type and physical instance remain distinct; schedules require source tables',()=>{
  assert.equal(door.width_m,.9);assert.equal(door.height_m,2.1);
  assert.equal(door.operation,'SINGLE_SWING_LEFT');assert.equal(door.wall_id,wall.id);
  const type=doc.types.find(t=>t.id===door.type_id);
  assert.equal(type.entity_kind,'door');assert.equal(type.name,'Single 900');
  assert.deepEqual(type.instance_ids,[door.id]);
  assert.equal(doc.schedules.length,0);
});
test('MEP membership resolves to canonical systems',()=>{
  const pipe=by('objects','0pipe1'),system=doc.systems.find(s=>s.id===pipe.system_ids[0]);
  assert.equal(pipe.ifc_class,'IfcPipeSegment');assert.equal(system.system_type,'plumbing');
  assert.equal(system.name,'Cold water');assert.deepEqual(system.component_ids,[pipe.id]);
});
test('slabs and products without a footprint are retained without invented geometry',()=>{
  assert.equal(by('objects','0slab1').category,'slab');
  const terminal=by('objects','0ft1');assert.ok(terminal);assert.equal(terminal.polygon_m,null);
  assert.equal(terminal.geometry.footprints.length,0);
});
test('--schema 0.2 is preserved and upgrades non-destructively to canonical v0.3',async()=>{
  const r2=await run('legacy.json',{configOverrides:{schemaVersion:'0.2'}});
  const d2=await read(r2.outputs[0].outputJsonPath);assert.equal(d2.schema_version,'0.2');assert.ok(v.validate(d2).valid);
  assert.ok(!d2.objects.some(o=>o.provenance.source_ref==='0slab1'));
  const r3=await run('legacy.json'),d3=await read(r3.outputs[0].outputJsonPath);
  assert.equal(r3.outputs[0].action,'merged');assert.equal(d3.schema_version,'0.3');assert.deepEqual(v.describe(v.validate(d3)),[]);
  assert.ok(d3.objects.some(o=>o.ifc_global_id==='0slab1'));assert.equal(d3.walls.length,1);
  await assert.rejects(run('legacy.json',{configOverrides:{schemaVersion:'0.2'}}),/refusing to merge a schema 0.2 extraction/);
});
