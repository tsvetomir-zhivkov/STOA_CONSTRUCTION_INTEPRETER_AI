import fs from 'node:fs';
import path from 'node:path';
import {fileURLToPath} from 'node:url';
import {spawn} from 'node:child_process';
const root=path.resolve(path.dirname(fileURLToPath(import.meta.url)),'../..');
const local=path.join(root,'.venv',process.platform==='win32'?'Scripts/python.exe':'bin/python');
const python=process.env.PYTHON ?? (fs.existsSync(local)?local:'python');
const child=spawn(python,['-m','workspace.server',...process.argv.slice(2)],{cwd:root,stdio:'inherit'});
child.on('exit',code=>{process.exitCode=code??0;});
child.on('error',error=>{console.error(error.message);process.exitCode=1;});
for(const event of ['SIGINT','SIGTERM'])process.on(event,()=>child.kill(event));
